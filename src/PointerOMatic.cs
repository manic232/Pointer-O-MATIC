        // Arrow keys nudge the arrow by 1 pixel (10 with Shift) for fine positioning.
        protected override bool ProcessCmdKey(ref Message msg, Keys keyData)
        {
            int step = (keyData & Keys.Shift) == Keys.Shift ? 10 : 1;
            int dx = 0, dy = 0;
            switch (keyData & Keys.KeyCode)
            {
                case Keys.Left: dx = -step; break;
                case Keys.Right: dx = step; break;
                case Keys.Up: dy = -step; break;
                case Keys.Down: dy = step; break;
            }
            if (dx != 0 || dy != 0)
            {
                Render(new Rectangle(win.X + dx, win.Y + dy, win.Width, win.Height));
                SavePosition();
                return true;
            }
            return base.ProcessCmdKey(ref msg, keyData);
        }

