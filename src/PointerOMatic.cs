        void FillOnlyInMenu()
        {
            var items = miOnlyIn.DropDownItems;
            var old = new ToolStripItem[items.Count];
            items.CopyTo(old, 0);
            items.Clear();
            foreach (var it in old)
            {
                if (it.Image != null) it.Image.Dispose();
                it.Dispose();
            }

            var any = new ToolStripMenuItem("&Any Window", null, (s, e) => SetOnlyApp("", ""));
            any.Checked = onlyApp.Length == 0;
            items.Add(any);
            items.Add(new ToolStripSeparator());

            bool found = false;
            foreach (var app in OpenApps.List())
            {
                string exe = app.Exe, name = app.Name;
                var item = new ToolStripMenuItem(name.Replace("&", "&&"), null, (s, e) => SetOnlyApp(exe, name));
                item.ToolTipText = exe;
