        [DllImport("user32.dll")] static extern uint MapVirtualKey(uint code, uint mapType);
        [DllImport("user32.dll", CharSet = CharSet.Unicode)] static extern int GetKeyNameText(int lParam, StringBuilder sb, int size);

        // Friendly key name as Windows shows it, e.g. "Q", "F2", "Scroll Lock", "Insert".
        public static string KeyName(Keys k)
        {
            switch (k)
            {
                case Keys.ShiftKey: return "Shift";
                case Keys.ControlKey: return "Ctrl";
                case Keys.Menu: return "Alt";
                case Keys.Pause: return "Pause";
            }
            uint scan = MapVirtualKey((uint)k, 0);
            if (scan != 0)
            {
                int lParam = (int)(scan << 16);
                switch (k)
                {
                    // These share scan codes with the number pad, so mark them as "extended" keys.
                    case Keys.Insert: case Keys.Delete: case Keys.Home: case Keys.End:
                    case Keys.PageUp: case Keys.PageDown: case Keys.Left: case Keys.Right:
                    case Keys.Up: case Keys.Down: case Keys.NumLock: case Keys.Divide:
                    case Keys.LWin: case Keys.RWin: case Keys.Apps:
                        lParam |= 1 << 24;
                        break;
                }
                var sb = new StringBuilder(64);
                if (GetKeyNameText(lParam, sb, sb.Capacity) > 0) return sb.ToString();
            }
            return k.ToString();
        }
    }

    // A key combination such as Ctrl+Alt+Space, stored as WinForms Keys (key code plus modifier flags).
    static class HotKey
    {
        static System.Collections.Generic.List<string> ModifierNames(Keys keys)
        {
            var parts = new System.Collections.Generic.List<string>();
            if ((keys & Keys.Control) != 0) parts.Add("Ctrl");
            if ((keys & Keys.Alt) != 0) parts.Add("Alt");
            if ((keys & Keys.Shift) != 0) parts.Add("Shift");
            return parts;
        }

        // For display, e.g. "Ctrl+Alt+Space". With only modifiers, e.g. "Ctrl+Alt+...".
        public static string Name(Keys keys)
        {
            if (keys == Keys.None) return "None";
            var parts = ModifierNames(keys);
            Keys k = keys & Keys.KeyCode;
            parts.Add(k == Keys.None ? "…" : KeyForm.KeyName(k));
            return string.Join("+", parts.ToArray());
        }

        // For the .ini file, e.g. "Ctrl+Alt+Space", "F8" or "None".
        public static string ToIni(Keys keys)
        {
            if ((keys & Keys.KeyCode) == Keys.None) return "None";
            var parts = ModifierNames(keys);
            parts.Add((keys & Keys.KeyCode).ToString());
            return string.Join("+", parts.ToArray());
        }

        public static Keys Parse(string s, Keys def)
        {
            s = (s ?? "").Trim();
            if (s.Length == 0) return def;
            if (s.Equals("None", StringComparison.OrdinalIgnoreCase)) return Keys.None;
            Keys mods = Keys.None, key = Keys.None;
            foreach (var raw in s.Split('+'))
            {
                string p = raw.Trim();
                string lower = p.ToLowerInvariant();
                if (lower == "ctrl" || lower == "control") mods |= Keys.Control;
                else if (lower == "alt") mods |= Keys.Alt;
                else if (lower == "shift") mods |= Keys.Shift;
                else
                {
                    Keys k;
                    if (!Enum.TryParse(p, true, out k)) return def;
                    key = k & Keys.KeyCode;
                }
            }
            return key == Keys.None ? def : mods | key;
        }
    }

    // Finds the programs that have windows open on screen, for the Only In menu.
    static class OpenApps
    {
        public class App { public string Exe, Name; public Bitmap Icon; }

        delegate bool EnumWindowsProc(IntPtr hWnd, IntPtr lParam);
        [DllImport("user32.dll")] static extern bool EnumWindows(EnumWindowsProc fn, IntPtr lParam);
        [DllImport("user32.dll")] static extern bool IsWindowVisible(IntPtr hWnd);
        [DllImport("user32.dll")] static extern IntPtr GetWindow(IntPtr hWnd, uint cmd);
        [DllImport("user32.dll")] static extern int GetWindowTextLength(IntPtr hWnd);
        [DllImport("user32.dll")] static extern int GetWindowLong(IntPtr hWnd, int index);
        [DllImport("user32.dll")] static extern int GetWindowThreadProcessId(IntPtr hWnd, out int pid);
        [DllImport("dwmapi.dll")] static extern int DwmGetWindowAttribute(IntPtr hWnd, int attr, out int value, int size);
        [DllImport("kernel32.dll")] static extern IntPtr OpenProcess(uint access, bool inherit, int pid);
        [DllImport("kernel32.dll")] static extern bool CloseHandle(IntPtr h);
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode)]
        static extern bool QueryFullProcessImageName(IntPtr process, int flags, StringBuilder name, ref int size);

        const uint GW_OWNER = 4, PROCESS_QUERY_LIMITED_INFORMATION = 0x1000;
        const int GWL_EXSTYLE = -20, WS_EX_TOOLWINDOW = 0x80, DWMWA_CLOAKED = 14;

        // Full path of a program's .exe (works for most programs, including ones run as administrator).
        public static string ExePath(int pid)
        {
            IntPtr h = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, pid);
            if (h == IntPtr.Zero) return "";
            try
            {
                var sb = new StringBuilder(1024);
                int size = sb.Capacity;
                return QueryFullProcessImageName(h, 0, sb, ref size) ? sb.ToString() : "";
            }
            finally { CloseHandle(h); }
        }

        public static string ExeName(int pid)
        {
            string path = ExePath(pid);
            return path.Length == 0 ? "" : System.IO.Path.GetFileName(path);
        }

        // Windows you'd see on the taskbar or with Alt+Tab: visible, titled, not owned by another window,
        // not a tool window, and not hidden by Windows (as background Store apps are).
        static bool IsAppWindow(IntPtr h)
        {
            if (!IsWindowVisible(h) || GetWindow(h, GW_OWNER) != IntPtr.Zero || GetWindowTextLength(h) == 0) return false;
            if ((GetWindowLong(h, GWL_EXSTYLE) & WS_EX_TOOLWINDOW) != 0) return false;
            int cloaked;
            if (DwmGetWindowAttribute(h, DWMWA_CLOAKED, out cloaked, 4) == 0 && cloaked != 0) return false;
            return true;
        }

        public static System.Collections.Generic.List<App> List()
        {
            int ownPid = System.Diagnostics.Process.GetCurrentProcess().Id;
            var paths = new System.Collections.Generic.Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            EnumWindows((h, l) =>
            {
                if (!IsAppWindow(h)) return true;
                int pid;
                GetWindowThreadProcessId(h, out pid);
                if (pid == ownPid) return true;
                string path = ExePath(pid);
                if (path.Length > 0)
                {
                    string exe = System.IO.Path.GetFileName(path);
                    if (!paths.ContainsKey(exe)) paths[exe] = path;
                }
                return true;
            }, IntPtr.Zero);

            var apps = new System.Collections.Generic.List<App>();
            foreach (var kv in paths)
                apps.Add(new App { Exe = kv.Key, Name = FriendlyName(kv.Value), Icon = SmallIcon(kv.Value) });
            apps.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));
            return apps;
        }

        // "Vivaldi", "Notepad++", "Windows Explorer"... rather than the .exe name.
        static string FriendlyName(string path)
        {
            try
            {
                var info = System.Diagnostics.FileVersionInfo.GetVersionInfo(path);
                string name = (info.ProductName ?? "").Trim();
                if (name.Length == 0 || name.IndexOf("Operating System", StringComparison.OrdinalIgnoreCase) >= 0)
                    name = (info.FileDescription ?? "").Trim();
                name = name.Replace("®", "").Replace("™", "").Trim();
                if (name.Length > 0) return name;
            }
            catch { }
            return System.IO.Path.GetFileNameWithoutExtension(path);
        }

        static Bitmap SmallIcon(string path)
        {
            try
            {
                using (var icon = Icon.ExtractAssociatedIcon(path))
                {
                    if (icon == null) return null;
                    int s = SystemInformation.SmallIconSize.Width;
                    var bmp = new Bitmap(s, s, PixelFormat.Format32bppArgb);
                    using (var big = icon.ToBitmap())
                    using (var g = Graphics.FromImage(bmp))
                    {
                        g.InterpolationMode = InterpolationMode.HighQualityBicubic;
                        g.DrawImage(big, 0, 0, s, s);
                    }
                    return bmp;
                }
            }
            catch { return null; }
        }
    }

