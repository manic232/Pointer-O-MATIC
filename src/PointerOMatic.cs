        // Returns false if another program already uses the shortcut.
        bool RegisterToggleKey()
        {
            UnregisterToggleKey();
            if (toggleKey == Keys.None || !IsHandleCreated) return true;
            uint mods = MOD_NOREPEAT;
            if ((toggleKey & Keys.Control) != 0) mods |= MOD_CONTROL;
            if ((toggleKey & Keys.Alt) != 0) mods |= MOD_ALT;
            if ((toggleKey & Keys.Shift) != 0) mods |= MOD_SHIFT;
            toggleKeyRegistered = RegisterHotKey(Handle, HotKeyId, mods, (uint)(toggleKey & Keys.KeyCode));
            return toggleKeyRegistered;
        }

        void UnregisterToggleKey()
        {
            if (!toggleKeyRegistered) return;
            UnregisterHotKey(Handle, HotKeyId);
            toggleKeyRegistered = false;
        }

        void ToggleFollowFromShortcut()
        {
            SetFollow(!follow);
            // Following a hidden arrow is pointless, so bring it back (without taking focus from the current program).
            if (follow && !Visible)
            {
                // Showing the arrow gives it the focus; hand that straight back to the program you were using.
                IntPtr previous = GetForegroundWindow();
                Show();
                Render(win);
                if (previous != IntPtr.Zero && previous != Handle) SetForegroundWindow(previous);
            }
            // Bring the arrow back above any other always-on-top window that has covered it.
            if (Visible && TopMost) SetWindowPos(Handle, HWND_TOPMOST, 0, 0, 0, 0, SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE);
            ShowNotice("Follow Clicks: " + (follow ? "On" : "Off"));
        }

