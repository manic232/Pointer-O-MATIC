        protected override void OnRenderMenuItemBackground(ToolStripItemRenderEventArgs e)
        {
            if (!e.Item.Selected || !e.Item.Enabled) return;
            var r = new Rectangle(3, 1, e.Item.Width - 6, e.Item.Height - 2);
            e.Graphics.SmoothingMode = SmoothingMode.AntiAlias;
            using (var path = RoundRect(r, 4))
            using (var b = new SolidBrush(p.Hover))
                e.Graphics.FillPath(b, path);
        }

        protected override void OnRenderItemText(ToolStripItemTextRenderEventArgs e)
        {
            e.TextColor = e.Item.Enabled ? p.Text : p.TextDisabled;
            base.OnRenderItemText(e);
        }

        protected override void OnRenderArrow(ToolStripArrowRenderEventArgs e)
        {
            e.ArrowColor = p.Text;
            base.OnRenderArrow(e);
        }

        protected override void OnRenderSeparator(ToolStripSeparatorRenderEventArgs e)
        {
            int y = e.Item.Height / 2;
            using (var pen = new Pen(p.Separator))
                e.Graphics.DrawLine(pen, 8, y, e.Item.Width - 8, y);
        }

        // Draw our own tick so it shows up on a dark background.
        protected override void OnRenderItemCheck(ToolStripItemImageRenderEventArgs e)
        {
            var r = e.ImageRectangle;
            var g = e.Graphics;
            g.SmoothingMode = SmoothingMode.AntiAlias;
            using (var pen = new Pen(p.Text, Math.Max(1.6f, r.Height / 9f)) { StartCap = LineCap.Round, EndCap = LineCap.Round, LineJoin = LineJoin.Round })
            {
                g.DrawLines(pen, new[] {
                    new PointF(r.Left + r.Width * 0.20f, r.Top + r.Height * 0.52f),
                    new PointF(r.Left + r.Width * 0.42f, r.Top + r.Height * 0.74f),
                    new PointF(r.Left + r.Width * 0.80f, r.Top + r.Height * 0.28f) });
            }
        }

        static GraphicsPath RoundRect(Rectangle r, int radius)
        {
            int d = radius * 2;
            var path = new GraphicsPath();
            path.AddArc(r.Left, r.Top, d, d, 180, 90);
            path.AddArc(r.Right - d, r.Top, d, d, 270, 90);
            path.AddArc(r.Right - d, r.Bottom - d, d, d, 0, 90);
            path.AddArc(r.Left, r.Bottom - d, d, d, 90, 90);
            path.CloseFigure();
            return path;
        }
    }

    // Reads and writes the .ini file via the standard Windows API.
    class IniFile
    {
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode)]
        static extern int GetPrivateProfileString(string section, string key, string def, StringBuilder ret, int size, string path);
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode)]
        static extern bool WritePrivateProfileString(string section, string key, string val, string path);

        public readonly string Path;
        public IniFile(string path) { Path = path; }

        public bool Exists { get { return File.Exists(Path); } }

        public string Read(string section, string key, string def)
        {
            var sb = new StringBuilder(1024);
            GetPrivateProfileString(section, key, def, sb, sb.Capacity, Path);
            return sb.ToString();
        }

        public int ReadInt(string section, string key, int def)
        {
            int v;
            return int.TryParse(Read(section, key, ""), NumberStyles.Integer, CultureInfo.InvariantCulture, out v) ? v : def;
        }

        public bool ReadBool(string section, string key, bool def)
        {
            string s = Read(section, key, "").Trim().ToLowerInvariant();
            if (s == "1" || s == "true" || s == "yes") return true;
            if (s == "0" || s == "false" || s == "no") return false;
            return def;
        }

        public void Write(string section, string key, string value)
        {
            WritePrivateProfileString(section, key, value, Path);
        }

        public void Write(string section, string key, int value)
        {
            Write(section, key, value.ToString(CultureInfo.InvariantCulture));
        }

        public void Write(string section, string key, bool value)
        {
            Write(section, key, value ? "1" : "0");
        }
    }

