        // Small colour square shown next to a menu item.
        static void SetSwatch(ToolStripMenuItem item, Color c)
        {
            int s = Math.Max(12, SystemInformation.SmallIconSize.Height - 4);
            var bmp = new Bitmap(s, s);
            using (var g = Graphics.FromImage(bmp))
            {
                g.Clear(c);
                using (var p = new Pen(Color.FromArgb(128, 128, 128))) g.DrawRectangle(p, 0, 0, s - 1, s - 1);
            }
            var old = item.Image;
            item.Image = bmp;
            if (old != null) old.Dispose();
        }

