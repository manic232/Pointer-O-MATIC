                    found = true;
                    if (app.Icon != null) app.Icon.Dispose();
                }
                else if (app.Icon != null)
                {
                    item.Image = app.Icon;
                    item.ImageScaling = ToolStripItemImageScaling.None;
                }
                items.Add(item);
            }

            // The chosen program isn't open at the moment: still show it, so it's clear what's set.
            if (onlyApp.Length > 0 && !found)
                items.Insert(2, new ToolStripMenuItem(onlyAppName.Replace("&", "&&") + " (not open)") { Checked = true, ToolTipText = onlyApp });
