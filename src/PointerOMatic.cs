        // Keys that are fine as a shortcut on their own because they don't type or scroll.
        static bool SafeOnItsOwn(Keys k)
        {
            return (k >= Keys.F1 && k <= Keys.F24) || k == Keys.Pause || k == Keys.Scroll;
