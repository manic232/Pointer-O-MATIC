        void ChooseToggleKey()
        {
            Keys tryKey = toggleKey;
            UnregisterToggleKey();      // so the current shortcut can be pressed in the window
            while (true)
            {
                Keys chosen;
                using (var dlg = new KeyForm(tryKey, true))
                {
                    PlaceNearArrow(dlg);
                    if (dlg.ShowDialog(this) != DialogResult.OK) break;
                    chosen = dlg.SelectedKey;
                }
                tryKey = chosen;
                string name = HotKey.Name(chosen);

                if (chosen != Keys.None && (chosen & (Keys.Control | Keys.Alt)) == 0)
                {
                    if (followTrigger == FollowTrigger.KeyClick && chosen == followKey)
                    {
                        MessageBox.Show(this, name + " is the key you hold while clicking to move the arrow, so it can't also turn Follow Clicks on and off.\n\nPlease choose a different shortcut.",
                            "On/Off Shortcut", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                        continue;
                    }
                    if (!SafeOnItsOwn(chosen & Keys.KeyCode) &&
                        MessageBox.Show(this, "While Pointer-O-MATIC is running, pressing " + name + " in any program will only turn Follow Clicks on and off. " +
                            "It will stop doing its normal job everywhere else, such as typing or scrolling.\n\n" +
                            "Adding Ctrl or Alt avoids this. Use " + name + " on its own anyway?",
                            "On/Off Shortcut", MessageBoxButtons.YesNo, MessageBoxIcon.Warning, MessageBoxDefaultButton.Button2) != DialogResult.Yes)
                        continue;
                }

                Keys old = toggleKey;
                toggleKey = chosen;
                if (RegisterToggleKey())
                {
                    ini.Write(F, "ToggleKey", HotKey.ToIni(toggleKey));
                    return;
                }
                toggleKey = old;
                MessageBox.Show(this, name + " is already used by another program.\n\nPlease choose a different shortcut.",
                    "On/Off Shortcut", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            RegisterToggleKey();        // cancelled: put the old shortcut back
        }

