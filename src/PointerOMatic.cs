            PointF local = TipLocal();
            var size = WindowSize();
            Render(new Rectangle((int)Math.Round(tip.X - local.X), (int)Math.Round(tip.Y - local.Y), size.Width, size.Height));
            SavePosition();

            // Clicking another always-on-top window lifts it above the arrow; put the arrow back on top.
            if (TopMost && IsHandleCreated)
                SetWindowPos(Handle, HWND_TOPMOST, 0, 0, 0, 0, SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE);
        }

