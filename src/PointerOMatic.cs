        // ---------- Settings ----------

        void LoadSettings()
        {
            arrowW = Clamp(ini.ReadInt(S, "Width", 60), MinSize, MaxSize);
            arrowH = Clamp(ini.ReadInt(S, "Height", 30), MinSize, MaxSize);
            arrowColor = ParseColor(ini.Read(S, "Colour", ""), Color.Red);
            outline = ini.ReadBool(S, "Outline", true);
            string oc = ini.Read(S, "OutlineColour", "Auto").Trim();
            outlineAuto = oc.Equals("Auto", StringComparison.OrdinalIgnoreCase) || oc.Length == 0;
            outlineColor = ParseColor(oc, Color.Black);
            TopMost = ini.ReadBool(S, "AlwaysOnTop", true);

            Direction d;
            direction = Enum.TryParse(ini.Read(S, "Direction", "Right"), true, out d) ? d : Direction.Right;

            MenuTheme t;
            theme = Enum.TryParse(ini.Read("Menu", "Theme", "System"), true, out t) ? t : MenuTheme.System;

            follow = ini.ReadBool(F, "Enabled", false);
            FollowTrigger ft;
            followTrigger = Enum.TryParse(ini.Read(F, "Trigger", "LeftClick"), true, out ft) ? ft : FollowTrigger.LeftClick;
            FollowMode fm;
            followMode = Enum.TryParse(ini.Read(F, "Mode", "Beside"), true, out fm) ? fm : FollowMode.Beside;
            ClickSide cs;
            followSide = Enum.TryParse(ini.Read(F, "Side", "Right"), true, out cs) ? cs : ClickSide.Right;
            followDistance = Clamp(ini.ReadInt(F, "Distance", 20), 0, OffsetForm.MaxDistance);
            Keys k;
            followKey = Enum.TryParse(ini.Read(F, "Key", "Q"), true, out k) && k != Keys.None ? k : Keys.Q;
            toggleKey = HotKey.Parse(ini.Read(F, "ToggleKey", ""), DefaultToggleKey);
            onlyApp = ini.Read(F, "OnlyApp", "").Trim();
            onlyAppName = ini.Read(F, "OnlyAppName", "").Trim();
            if (onlyAppName.Length == 0) onlyAppName = onlyApp;

            string cc = ini.Read("CustomColours", "List", "");
            if (cc.Length > 0)
            {
                var parts = cc.Split(',');
                var list = new System.Collections.Generic.List<int>();
                foreach (var p in parts)
                {
                    int v;
                    if (int.TryParse(p.Trim(), out v)) list.Add(v);
                }
                customColors = list.ToArray();
            }

            var size = WindowSize();
            int x = ini.ReadInt(S, "X", int.MinValue);
            int y = ini.ReadInt(S, "Y", int.MinValue);
            var rect = new Rectangle(x, y, size.Width, size.Height);

            // First run, or saved spot is no longer on any screen: centre on the main screen.
            if (x == int.MinValue || y == int.MinValue || !IsOnAnyScreen(rect))
            {
                var wa = Screen.PrimaryScreen.WorkingArea;
                rect.X = wa.Left + (wa.Width - size.Width) / 2;
                rect.Y = wa.Top + (wa.Height - size.Height) / 2;
            }
            win = rect;
            Bounds = rect;
        }

