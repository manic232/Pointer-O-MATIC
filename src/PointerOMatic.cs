        void PickArrowColour()
        {
            Color c;
            if (ChooseColour(arrowColor, out c))
            {
                arrowColor = c;
                ini.Write(S, "Colour", ColorToHex(arrowColor));
                Render(win);
                UpdateTrayIcon();
            }
        }

        void PickOutlineColour()
        {
            Color c;
            if (ChooseColour(CurrentOutlineColour(false), out c))
            {
                outlineColor = c;
                outlineAuto = false;
                outline = true;
                SaveOutlineColour();
                ini.Write(S, "Outline", true);
                Render(win);
                UpdateTrayIcon();
            }
        }

        bool ChooseColour(Color current, out Color result)
        {
            using (var dlg = new ColorDialog())
            {
                dlg.Color = current;
                dlg.FullOpen = true;
                dlg.AnyColor = true;
                if (customColors.Length > 0) dlg.CustomColors = customColors;
                bool ok = dlg.ShowDialog(this) == DialogResult.OK;
                result = dlg.Color;
                customColors = dlg.CustomColors;
                ini.Write("CustomColours", "List", string.Join(",", Array.ConvertAll(customColors, c => c.ToString(CultureInfo.InvariantCulture))));
                return ok;
            }
        }

        // ---------- Menu theme ----------

        void SetTheme(MenuTheme t)
        {
            theme = t;
            ini.Write("Menu", "Theme", t.ToString());
            ApplyTheme();
        }

        bool MenuIsDark()
        {
            return theme == MenuTheme.Dark || (theme == MenuTheme.System && ThemedRenderer.WindowsUsesDarkMode());
        }

        void ApplyTheme()
        {
            // Applies to the right-click menu and all its sub-menus.
            ToolStripManager.Renderer = new ThemedRenderer(MenuIsDark());
        }

        void OnUserPreferenceChanged(object sender, Microsoft.Win32.UserPreferenceChangedEventArgs e)
        {
            if (theme != MenuTheme.System || !IsHandleCreated) return;
            BeginInvoke((MethodInvoker)ApplyTheme);
        }

        // ---------- Tray icon ----------

        void BuildTray()
        {
            tray = new NotifyIcon();
            tray.Text = "Pointer-O-MATIC";
            tray.ContextMenuStrip = menu;
            tray.MouseClick += (s, e) =>
            {
                // Left-click: show the arrow and bring it to the front.
                if (e.Button == MouseButtons.Left) SetArrowVisible(true);
            };
            UpdateTrayIcon();
            UpdateTrayText();
            tray.Visible = true;
        }

        void UpdateTrayText()
        {
