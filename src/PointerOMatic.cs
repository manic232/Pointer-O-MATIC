        // Moves the arrow for a click at screen point p, according to the follow settings.
        void PlaceForClick(Point p)
        {
            lastClick = p;
            hasLastClick = true;

            PointF tipLocal = TipLocal();
            float tipX = win.X + tipLocal.X, tipY = win.Y + tipLocal.Y;

            switch (followMode)
            {
                case FollowMode.UpDown:
                    PlaceTip(new PointF(tipX, p.Y), direction);
                    break;
                case FollowMode.LeftRight:
                    PlaceTip(new PointF(p.X, tipY), direction);
                    break;
                default:
                    // Put the tip on the chosen side of the click; keep the direction set in the Direction menu.
                    int d = followDistance;
                    switch (followSide)
                    {
                        case ClickSide.Left: PlaceTip(new PointF(p.X - d, p.Y), direction); break;
                        case ClickSide.Above: PlaceTip(new PointF(p.X, p.Y - d), direction); break;
                        case ClickSide.Below: PlaceTip(new PointF(p.X, p.Y + d), direction); break;
                        default: PlaceTip(new PointF(p.X + d, p.Y), direction); break;
                    }
                    break;
            }
        }

        // Puts the arrow's tip exactly at 'tip' (screen coordinates), pointing in direction d.
        void PlaceTip(PointF tip, Direction d)
        {
            if (d != direction)
            {
                bool wasHorizontal = IsHorizontal(direction);
                direction = d;
                if (wasHorizontal != IsHorizontal(d)) { int t = arrowW; arrowW = arrowH; arrowH = t; }
                ini.Write(S, "Direction", d.ToString());
                SaveSize();
                if (sizeForm != null && !sizeForm.IsDisposed) sizeForm.SyncFromArrow();
