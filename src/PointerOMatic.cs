        const int WH_MOUSE_LL = 14, VK_CONTROL = 0x11;
        const int WM_LBUTTONDOWN = 0x201, WM_LBUTTONUP = 0x202, WM_MBUTTONDOWN = 0x207, WM_MBUTTONUP = 0x208;

        LowLevelMouseProc hookProc;     // kept in a field so it isn't garbage collected
        IntPtr hook = IntPtr.Zero;
        Point downPoint;
        bool downValid;

        void InstallMouseHook()
        {
            if (hook != IntPtr.Zero) return;
            hookProc = MouseHookProc;
            hook = SetWindowsHookEx(WH_MOUSE_LL, hookProc, GetModuleHandle(null), 0);
        }

        void RemoveMouseHook()
        {
            if (hook == IntPtr.Zero) return;
            UnhookWindowsHookEx(hook);
            hook = IntPtr.Zero;
            downValid = false;
        }

        IntPtr MouseHookProc(int nCode, IntPtr wParam, IntPtr lParam)
        {
            if (nCode >= 0)
            {
                try
                {
                    var info = (MSLLHOOKSTRUCT)Marshal.PtrToStructure(lParam, typeof(MSLLHOOKSTRUCT));
                    OnGlobalMouse((int)wParam, info.pt);
                }
                catch { }
            }
            return CallNextHookEx(hook, nCode, wParam, lParam);
        }

        void OnGlobalMouse(int msg, POINT raw)
        {
            bool middle = followTrigger == FollowTrigger.MiddleClick;
            bool isDown = msg == (middle ? WM_MBUTTONDOWN : WM_LBUTTONDOWN);
            bool isUp = msg == (middle ? WM_MBUTTONUP : WM_LBUTTONUP);
            if (!isDown && !isUp) return;

            // Hook coordinates are physical pixels; convert to the same coordinates the arrow uses.
            POINT pt = raw;
            try { if (IsHandleCreated) PhysicalToLogicalPointForPerMonitorDPI(Handle, ref pt); } catch { }
            var p = new Point(pt.X, pt.Y);

            if (isDown)
            {
                bool keyOk = true;
                if (followTrigger == FollowTrigger.CtrlClick) keyOk = (GetAsyncKeyState(VK_CONTROL) & 0x8000) != 0;
                else if (followTrigger == FollowTrigger.KeyClick) keyOk = (GetAsyncKeyState((int)followKey) & 0x8000) != 0;
                downValid = keyOk && ClickCounts(pt);
                downPoint = p;
            }
            else if (downValid)
            {
                downValid = false;
                // Only a click, not a drag (e.g. selecting text or dragging the scrollbar).
                var drag = SystemInformation.DragSize;
                if (Math.Abs(p.X - downPoint.X) <= drag.Width && Math.Abs(p.Y - downPoint.Y) <= drag.Height && IsHandleCreated)
                {
                    Point target = downPoint;
                    BeginInvoke((MethodInvoker)(() => PlaceForClick(target)));
                }
            }
        }

        static readonly int OwnPid = System.Diagnostics.Process.GetCurrentProcess().Id;
        [DllImport("user32.dll")] static extern IntPtr GetAncestor(IntPtr hWnd, uint flags);
        const uint GA_ROOT = 2;

        // Ignore clicks on the arrow itself and on its own menus and windows, and,
        // when Only In is set, clicks in any other program.
        bool ClickCounts(POINT pt)
        {
            IntPtr window = GetAncestor(WindowFromPoint(pt), GA_ROOT);
            int pid;
            GetWindowThreadProcessId(window, out pid);
            if (pid == OwnPid) return false;
            if (onlyApp.Length == 0) return true;
            return onlyApp.Equals(OpenApps.ExeName(pid), StringComparison.OrdinalIgnoreCase);
        }

