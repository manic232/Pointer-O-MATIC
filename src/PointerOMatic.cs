        static bool IsHorizontal(Direction d) { return d == Direction.Left || d == Direction.Right; }

        Size WindowSize() { return new Size(arrowW + Pad * 2, arrowH + Pad * 2); }

        // x runs along the arrow (0 = tail, len = tip), y across it; box is where the arrow sits.
        static PointF Map(float x, float y, float len, RectangleF box, Direction d)
        {
            switch (d)
            {
                case Direction.Left: return new PointF(box.X + len - x, box.Y + y);
                case Direction.Down: return new PointF(box.X + y, box.Y + x);
                case Direction.Up: return new PointF(box.X + y, box.Y + len - x);
                default: return new PointF(box.X + x, box.Y + y);
            }
        }

        static void LengthThickness(RectangleF box, Direction d, out float len, out float thick)
        {
            if (IsHorizontal(d)) { len = box.Width; thick = box.Height; }
            else { len = box.Height; thick = box.Width; }
        }

        RectangleF ArrowBox() { return new RectangleF(Pad, Pad, arrowW, arrowH); }

        PointF TipLocal()
        {
            var box = ArrowBox();
            float len, thick;
            LengthThickness(box, direction, out len, out thick);
            return Map(len, thick / 2f, len, box, direction);
        }

        static GraphicsPath ArrowPath(RectangleF box, Direction d)
        {
            float len, thick;
            LengthThickness(box, d, out len, out thick);

            float head = Math.Min(len * 0.55f, thick * 0.9f);
            float shaft = thick * 0.45f;
            float s1 = (thick - shaft) / 2f, s2 = (thick + shaft) / 2f;
            float hx = len - head;

            var pts = new[] {
                Map(0, s1, len, box, d), Map(hx, s1, len, box, d), Map(hx, 0, len, box, d),
                Map(len, thick / 2f, len, box, d),
                Map(hx, thick, len, box, d), Map(hx, s2, len, box, d), Map(0, s2, len, box, d)
            };
            var path = new GraphicsPath();
            path.AddPolygon(pts);
            return path;
        }

        // The outline colour in use. With 'automatic', black or white depending on the arrow colour.
        Color CurrentOutlineColour(bool forDrawing)
        {
            if (!outlineAuto) return outlineColor;
            double lum = 0.299 * arrowColor.R + 0.587 * arrowColor.G + 0.114 * arrowColor.B;
            if (lum > 140) return forDrawing ? Color.FromArgb(200, 0, 0, 0) : Color.Black;
            return forDrawing ? Color.FromArgb(220, 255, 255, 255) : Color.White;
        }

